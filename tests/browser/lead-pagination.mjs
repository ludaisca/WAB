import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const origin=process.env.WAB_TEST_ORIGIN||'http://ludaisca:17100';
const sessions=JSON.parse(fs.readFileSync(process.env.WAB_TEST_SESSIONS||'/review/sessions.json','utf8'));
const rows=Array.from({length:5101},(_,i)=>({id:`lead-${i}`,score:80,label:i%2?'frio':'interesado',summary:'Resumen de prueba',reasons:'[]',details:null,updatedAt:'2026-10-23T16:00:00Z',scorer:{id:'scorer',name:'Calificador de prueba'},campaign:null,chat:{id:`chat-${i}`,name:`Lead ${String(i).padStart(4,'0')}`,remoteJid:'520000000000@s.whatsapp.net',accountId:'account',status:'OPEN',account:{id:'account',name:'Cuenta de prueba',origen:null,leadIdPrefix:null},contact:null,publicLink:'https://example.invalid/c/synthetic',lastInboundAt:null}}));
const browser=await chromium.launch({headless:true});
try{
const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
await context.addCookies([{name:'authjs.session-token',value:sessions.admin,domain:new URL(origin).hostname,path:'/'}]);
const page=await context.newPage();const errors=[];const queries=[];
page.on('pageerror',err=>errors.push(err.message));
await page.route('**/api/whatsapp/lead-scorers',route=>route.fulfill({json:[]}));
await page.route('**/api/whatsapp/lead-scores?*',async route=>{
 const params=new URL(route.request().url()).searchParams;queries.push(params.toString());
 let filtered=rows;
 if(params.has('label'))filtered=filtered.filter(r=>r.label===params.get('label'));
 if(params.has('ids'))filtered=filtered.filter(r=>params.get('ids').split(',').includes(r.id));
 const pageNumber=Number(params.get('page'));const size=Number(params.get('pageSize'));
 await route.fulfill({json:{items:filtered.slice((pageNumber-1)*size,pageNumber*size),total:filtered.length,page:pageNumber,pageSize:size,options:{scorers:[{id:'scorer',name:'Calificador de prueba'}],accounts:[{id:'account',name:'Cuenta de prueba'}]}}});
});
await page.goto(`${origin}/whatsapp/calificadores`,{waitUntil:'networkidle'});
await page.getByRole('tab',{name:'Leads calificados',exact:true}).click();
await page.getByText('5,101 calificaciones encontradas',{exact:true}).waitFor();
await page.getByRole('checkbox',{name:'Seleccionar Lead 0000',exact:true}).check();
await page.getByRole('button',{name:'Página siguiente',exact:true}).click();
await page.getByRole('checkbox',{name:'Seleccionar Lead 0025',exact:true}).check();
await page.getByRole('button',{name:'Exportar CSV',exact:true}).click();
await page.getByRole('radio',{name:/Seleccionados/}).check();
let downloadPromise=page.waitForEvent('download');
await page.getByRole('button',{name:'Exportar',exact:true}).click();
let download=await downloadPromise;let csv=fs.readFileSync(await download.path(),'utf8');
assert.ok(csv.includes('Lead 0000'));assert.ok(csv.includes('Lead 0025'));assert.ok(!csv.includes('Lead 0001'));
console.log('PASS selection and CSV export span multiple pages');
await page.getByRole('button',{name:'Exportar CSV',exact:true}).click();
await page.getByRole('radio',{name:/Todos los resultados/}).check();
downloadPromise=page.waitForEvent('download');
await page.getByRole('button',{name:'Exportar',exact:true}).click();
download=await downloadPromise;csv=fs.readFileSync(await download.path(),'utf8');
assert.ok(csv.includes('Lead 5100'));assert.equal(csv.split('\r\n').length,5102);
console.log('PASS full CSV includes all 5,101 results beyond the legacy 5,000 cap');
await page.getByRole('combobox',{name:'Calificación',exact:true}).selectOption('frio');
await page.getByText('2,550 calificaciones encontradas',{exact:true}).waitFor();
assert.ok(queries.at(-1).includes('label=frio'));assert.ok(queries.at(-1).includes('page=1'));
await page.getByRole('combobox',{name:'Cuenta',exact:true}).selectOption('account');
await page.getByRole('combobox',{name:'Calificador',exact:true}).selectOption('scorer');
await page.waitForResponse(res=>res.url().includes('/lead-scores?')&&res.url().includes('scorerId=scorer'));
await page.setViewportSize({width:390,height:844});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile leads must fit viewport');
await page.screenshot({path:'/review/leads-mobile-synthetic.png'});
console.log('PASS server filters, stable catalogs and mobile layout');
assert.deepEqual(errors,[]);
}finally{await browser.close();}
